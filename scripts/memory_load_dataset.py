def build_dataset(now):
    previous_month = (now.year - 1, 12) if now.month == 1 else (now.year, now.month - 1)
    month = now.replace(year=previous_month[0], month=previous_month[1],
                        day=min(now.day, calendar.monthrange(*previous_month)[1]))
    buckets = [('1d', now - timedelta(days=1)), ('3d', now - timedelta(days=3)),
               ('7d', now - timedelta(days=7)), ('1m', month)]
    cases = [(domain, text, query) for domain, rows in [('生活', LIFE), ('工作', WORK), ('学习', STUDY)]
             for text, query in rows]
    assert len(cases) == 100, len(cases)
    memories, questions = [], []
    for bucket, day in buckets:
        for index, (domain, text, query) in enumerate(cases):
            key = f'{bucket}-{index:03d}'
            stamp = day.replace(hour=8 + index // 10, minute=(index % 10)*5, second=0, microsecond=0)
            memories.append(dict(key=key, bucket=bucket, domain=domain, text=text,
                                 occurred_at=stamp.isoformat(), title=text[:24],
                                 selected_for_publication=index in (1, 6, 25, 35, 42, 53, 70, 80),
                                 source_window=f'{bucket}-{index // 10:02d}'))
            if index in tuple(range(0, 10)) + tuple(range(34, 44)) + tuple(range(68, 78)):
                questions.append(dict(key=key, bucket=bucket, domain=domain,
                                      query=f'{day.date().isoformat()}那天，{query}',
                                      expected_keys=[key], kind='dated_paraphrase'))
    # Undated semantic questions accept the same activity on any of the four dates.
    for index in (2, 8, 10, 15, 18, 25, 34, 35, 38, 39, 43, 44, 48, 53, 58, 68, 69, 70, 73, 76, 78, 80, 85, 91):
        questions.append(dict(key=f'general-{index:03d}', query=cases[index][2],
                              expected_keys=[f'{bucket}-{index:03d}' for bucket, _ in buckets],
                              kind='undated_paraphrase'))
    return memories, questions
